        "There are no declarations without rules.",
        "",
        "---",
        "",
        "## 4. The Founder Dashboard, in words (four panels)",
        "",
        "**Panel ① Customer Pyramid.** Value is concentrated: Platinum + Gold "
        f"customers (top 50% by tier) hold the vast majority of the "
        f"${m['total_projected_clv']/1e6:.1f}M projected CLV pool. A retention "
        "failure at the top is much costlier than any acquisition win.",
        "",
        "**Panel ② Promo Dependency × Retention (by persona).** The most "
        "valuable cohorts (Premium Loyalist, Loyal Full-Price) sit in the "
        "High-Loyalty / Low-Promo quadrant — the *healthy core*. "
        "Promo-Dependent High-Value sits in High-Loyalty / High-Promo — "
