        "---",
        "",
        "## 1. The verdict",
        "",
        _build_verdict(m),
        "",
        "---",
        "",
        "## 2. Headline numbers",
        "",
        f"- **Customers analysed:** {m['customers']:,}",
        f"- **Total projected CLV:** ${m['total_projected_clv']:,.0f}",
        f"- **Top 20% of customers carry:** {m['top20_clv_share']}% of projected CLV",
        f"- **Customers discounted:** {m['pct_discounted']}%  →  **{m['discounted_clv_share']}% of CLV is discount-attached**",
        f"- **Discount-dependent customers:** {m['discount_dependent_customers']:,}",
        f"- **Premium (top-20% CLV) customers:** {m['pct_premium']}%",
        f"- **Satisfied customers (rating ≥ 3.8):** {m['pct_satisfied']}%",
        f"- **Canonical loyalty definition:** {winner_label}",
        "",
